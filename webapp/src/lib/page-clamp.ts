/**
 * Прижимка индекса страницы к границам пагинации.
 *
 * Индекс страницы живёт в состоянии компонента, а объём выборки считает
 * сервер — между двумя запросами любой список может сжаться (резолв жалобы на
 * последней странице, удаление города, смена фильтра). Без прижимки подпись
 * «Страница 3 из 2» противоречит запрошенным данным, «Вперёд» уже
 * задизейблен, а список выглядит пустым, будто данных нет вовсе.
 *
 * Модуль намеренно чистый (без React): вся арифметика проверяется обычными
 * юнит-тестами, а DOM-поведение остаётся за e2e (Playwright).
 */

/**
 * Число страниц по объёму выборки. Пустой или отсутствующий список — это
 * одна страница, а не ноль: иначе футер показывает «из 0».
 */
export function countPages(total: number, pageSize: number): number {
  // Незащитный pageSize дал бы бесконечность — молчаливый неверный футер.
  if (!Number.isFinite(pageSize) || pageSize <= 0) return 1;
  return Math.max(1, Math.ceil(Math.max(0, total) / pageSize));
}

/**
 * Прижимает индекс страницы к диапазону [1, totalPages]. Идемпотентно:
 * clamp(clamp(p, m), m) === clamp(p, m), поэтому безопасно звать повторно.
 */
export function clampPageIndex(page: number, totalPages: number): number {
  const last = Math.max(1, Math.floor(totalPages));
  return Math.min(Math.max(1, Math.floor(page)), last);
}
