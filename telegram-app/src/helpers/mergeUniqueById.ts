// Слияние страниц OFFSET-пагинации в один список без повторов.
//
// `GET /trips` и `GET /ride-requests` сортируются по времени/DATE_DESC и
// используют `skip/take`. Данные при этом ЖИВЫЕ: новая поездка или заявка
// встаёт в начало и сдвигает всё окно на одну строку. Предзагрузка следующей
// страницы идёт по `rootMargin: 320px`, то есть следующая страница грузится,
// пока предыдущая ещё на экране, — граничная строка успевает прийти дважды.
//
// Симптомы без слияния: одна карточка отрисована дважды (и React ругается на
// дубликат `key`), а последняя поездка ленты не показывается никогда.
//
// Ключевая страница (notifications, bookings по заявкам) защищена тем, что
// там курсор по id, а не смещение: сдвиг окна её не задевает. Поэтому
// слияние нужно именно там, где `skip/take`.

/**
 * Разворачивает страницы в один массив, оставляя ПЕРВОЕ вхождение id.
 *
 * Первое, а не последнее: страницы отдаются от самой свежей к самой старой,
 * и при повторе граничной строки актуальная копия — та, что пришла раньше.
 */
export function mergeUniqueById<T extends { id: string }>(
  pages: ReadonlyArray<{ items: readonly T[] }> | undefined,
): T[] {
  if (!pages) return [];
  const seen = new Set<string>();
  const merged: T[] = [];
  for (const page of pages) {
    for (const item of page.items ?? []) {
      if (seen.has(item.id)) continue;
      seen.add(item.id);
      merged.push(item);
    }
  }
  return merged;
}
