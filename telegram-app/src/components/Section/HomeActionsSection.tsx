import { IconContainer } from "@telegram-apps/telegram-ui";
import { CarFront, Users } from "lucide-react";
import { Section } from "@/ui/Section";
import { MenuRow } from "@/ui/MenuRow";

/**
 * Быстрые действия главной: «Создать поездку» (водитель) и «Ищу попутку»
 * (пассажир).
 *
 * Раньше это были два промо-блока на `ui/EmptyState` — то есть на
 * `Placeholder`, компоненте ПУСТОГО состояния: крупный центрированный
 * заголовок 24px, описание и кнопка. Два таких блока подряд занимали ~460px
 * и читались как «здесь пока ничего нет», хотя это два главных действия
 * продукта. `Placeholder` для действия — та же ошибка роли, что была у
 * попапа жалобы (реестр #35): пустое состояние и призыв к действию — разные
 * роли.
 *
 * Теперь — обычная секция со строками `ui/MenuRow`: тот же язык, что у меню
 * профиля. Вопрос «Едете на машине?» остался подписью строки (он объясняет,
 * КОМУ действие), а не полуэкранным заголовком.
 *
 * Два действия, а не одно: водитель и пассажир — разные сценарии, и
 * объединять их в одну кнопку нельзя (тест `HomePage.rideRequests` это
 * стережёт).
 *
 * Подпись строки — только ВОПРОС («Едете на машине?»): он объясняет, кому
 * действие, и это минимум текста. Благо выигрывает и ширина — у `MenuRow`
 * подпись обрезается многоточием на ~30 символах, а длинное объяснение
 * («Найдём попутчиков в дорогу по области») превращалось в «Едете на
 * машине? Найдём п…», то есть обрезался ровно на первом полезном слове.
 * Что происходит дальше, человек узнает на форме.
 */
export function HomeActionsSection({
  onCreateTrip,
  onFindRide,
}: {
  onCreateTrip: () => void;
  onFindRide: () => void;
}) {
  return (
    <Section header="Быстрые действия">
      <MenuRow
        label="Создать поездку"
        icon={
          <IconContainer>
            <CarFront size={18} aria-hidden />
          </IconContainer>
        }
        title="Создать поездку"
        subtitle="Едете на машине?"
        onClick={onCreateTrip}
      />
      <MenuRow
        label="Ищу попутку"
        icon={
          <IconContainer>
            <Users size={18} aria-hidden />
          </IconContainer>
        }
        title="Ищу попутку"
        subtitle="Нужна попутка?"
        onClick={onFindRide}
      />
    </Section>
  );
}
