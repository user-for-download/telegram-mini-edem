import { describe, expect, it } from "vitest";

import { plural } from "@/utils/plural";

describe("plural", () => {
  it("выбирает форму по последней цифре", () => {
    expect(plural(1, "место", "места", "мест")).toBe("место");
    expect(plural(2, "место", "места", "мест")).toBe("места");
    expect(plural(4, "место", "места", "мест")).toBe("места");
    expect(plural(5, "место", "места", "мест")).toBe("мест");
    expect(plural(11, "место", "места", "мест")).toBe("мест");
    expect(plural(0, "место", "места", "мест")).toBe("мест");
  });

  it("не путает 21/22/24 с 11/12/14", () => {
    // Хвост 11..14 всегда множественного — иначе «11 места».
    expect(plural(12, "место", "места", "мест")).toBe("мест");
    expect(plural(13, "место", "места", "мест")).toBe("мест");
    expect(plural(14, "место", "места", "мест")).toBe("мест");
    // …но 21/22/24 снова по хвосту.
    expect(plural(21, "место", "места", "мест")).toBe("место");
    expect(plural(22, "место", "места", "мест")).toBe("места");
    expect(plural(24, "место", "места", "мест")).toBe("места");
    expect(plural(111, "место", "места", "мест")).toBe("мест");
  });

  it("переносит правило на другой корень", () => {
    expect(plural(1, "отзыв", "отзыва", "отзывов")).toBe("отзыв");
    expect(plural(3, "отзыв", "отзыва", "отзывов")).toBe("отзыва");
    expect(plural(7, "отзыв", "отзыва", "отзывов")).toBe("отзывов");
  });
});
