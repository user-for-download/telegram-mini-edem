/**
 * Русское склонение существительного после числительного.
 *
 * Формы: 1 место / 2 места / 5 мест, 21 место, но 11 мест.
 * Правило: последняя цифра даёт форму, кроме «1..4» на 11..14 — там
 * всегда форма множественного (`n % 100` в 11..14 отсекает 11/21/31… не
 * доходит, потому что `% 10` у них 1..4, а `% 100` уводит в «много»).
 *
 * Возвращает только слово: вызов пишется как `${n} ${plural(n, "место", "места", "мест")}`.
 */
export function plural(
  n: number,
  one: string,
  few: string,
  many: string,
): string {
  const abs = Math.abs(n);
  const mod10 = abs % 10;
  const mod100 = abs % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
