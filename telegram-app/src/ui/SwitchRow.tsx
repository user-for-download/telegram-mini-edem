import type { ReactNode } from "react";
import { Switch } from "@telegram-apps/telegram-ui";
import { Cell } from "@/ui/Cell";
import styles from "./SwitchRow.module.css";

export interface SwitchRowProps {
  /**
   * Иконка строки — обёртывается в `<IconContainer>` вызывающим.
   *
   * Необязательна: не каждый экран, ставящий переключатель, несёт смысловую
   * иконку. Настройки профиля иконку имеют («тема», «звук» — узнаваемые
   * пиктограммы), а форма создания поездки обходится текстом: там уже есть
   * иконки у полей, и лишние пиктограммы у опций только шумят. Пустой слот
   * `before` кит не рисует, поэтому пропуск иконки не ломает раскладку.
   */
  icon?: ReactNode;
  /** Заголовок: имя настройки для глаза. */
  title: string;
  /** Подпись: одна строка, поясняет, что именно переключается. */
  subtitle: string;
  /** Текущее значение — единственный источник `checked` для `Switch`. */
  checked: boolean;
  /** Новый флаг; состояние переключателя — на стороне вызывающего. */
  onChange: (next: boolean) => void;
  /**
   * Имя переключателя для скринридера. Обычно равно `title`; отдельное поле
   * нужно, когда переключатель визуально назван иначе, чем звучит его
   * подпись.
   */
  label: string;
}

/**
 * Строка-переключатель: обычная `Cell`, `Switch` в слоте `after`.
 *
 * **Живёт в `ui/`, потому что правило нужно не одному экрану.** Первый
 * потребитель — настройки профиля (`pages/Profile`), второй — форма создания
 * поездки (`pages/CreateTrip`). Пока строка жила приватно в `ProfilePage`,
 * второе место было вынуждено скопировать её к себе, и копия рано или поздно
 * разъехалась бы с оригиналом (имя настройки, `role`, отсутствие кнопки).
 * Признак «нужно не одному экрану» — это и есть причина выноса: MEMORY §7 и
 * «Правило №5» в `ui/README.md`.
 *
 * Поверхность и разделители между строками даёт `Section` — свои рамки и
 * `Stack`-обёртка не нужны (и ломали разделители: `Section` ставит `Divider`
 * только между прямыми детьми). Поэтому у строки нет ни своей рамки, ни
 * фона: `width: 100%` при `content-box` плюс горизонтальный `padding` кита
 * дали бы вылет за правый край.
 *
 * **Строка НЕ кликабельна целиком.** Нативный `Switch` внутри `<button>` —
 * невалидная вложенность и двойное срабатывание на Enter/Space (реестр
 * #24), а `Component="button"` на `Cell` — это ровно та самая кнопка. Значит
 * фокус и Enter/Space есть только у самого `Switch`, а клик по строке мимо
 * него ничего не переключает. Инвариант закреплён тестом
 * `ui/__tests__/switchRow.test.tsx` — не по тексту, а по DOM.
 */
export function SwitchRow({
  icon,
  title,
  subtitle,
  checked,
  onChange,
  label,
}: SwitchRowProps) {
  return (
    <Cell
      before={icon}
      subtitle={subtitle}
      // Штатный режим кита «content without truncation» (Cell.d.ts:25).
      // ВКЛЮЧЁН ВСЕГДА, а не по требованию потребителя: подпись здесь — не
      // ярлык, а объяснение, и обрезанное объяснение врёт. Подпись опции
      // «Завершится после конца рейса, а не через сутки после отправления» —
      // 60 символов, самый длинный текст в приложении; при `nowrap` +
      // ellipsis (дефолт кита) многоточие съедало ровно смысловую часть —
      // «а не через сутки», то есть водитель читал бы противоположное.
      //
      // Именно поэтому это НЕ проп, как у `MenuRow`: там подпись — ярлык
      // («Мои заявки на попутку»), и каждая строка решает сама. Здесь любая
      // подпись объясняет последствие, поэтому решение одно на весь класс
      // компонентов, и.props означал бы «не забудь включить», что и есть
      // источник обрезанных строк.
      multiline
      after={
        <Switch
          // Настройка вкл/выкл — это switch по APG, а не чекбокс:
          // скринридер озвучивает «включено/выключено». aria-checked
          // руками не задаём: браузер выводит его из checked, а
          // дублирование рискует разойтись с реальным состоянием.
          role="switch"
          aria-label={label}
          checked={checked}
          onChange={(event) => onChange(event.target.checked)}
        />
      }
      // Фасадный компонент ВСЕГДА несёт свой класс — иначе общее правило
      // из SwitchRow.module.css окажется мёртвым (MEMORY §7: тот же класс
      // дефекта, что у ui/Card и ui/Field).
      className={styles.row}
    >
      {title}
    </Cell>
  );
}
